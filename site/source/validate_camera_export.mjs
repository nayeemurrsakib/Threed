import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const source=await fs.readFile(path.join(root,'viewer/renderer.js'),'utf8');
const {ObjectRenderer}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const bytes=await fs.readFile(path.join(root,'models/rangefinder-camera.glb'));
const original=bytes.buffer.slice(bytes.byteOffset,bytes.byteOffset+bytes.byteLength);
const inputView=new DataView(original),length=inputView.getUint32(12,true);
const document=JSON.parse(new TextDecoder().decode(new Uint8Array(original,20,length)));
const renderer=Object.create(ObjectRenderer.prototype);
Object.assign(renderer,{original,document,materials:structuredClone(document.materials),binOffset:28+length,state:{roughness:-1,metalness:-1}});
renderer.color('glass','#aec6cf');renderer.color('body','#f5f5f1');
const exported=await renderer.glb().arrayBuffer(),view=new DataView(exported);
assert.equal(view.getUint32(8,true),exported.byteLength);
const exportedDocument=JSON.parse(new TextDecoder().decode(new Uint8Array(exported,20,view.getUint32(12,true))));
const glass=exportedDocument.materials.find(m=>m.name==='glass');
assert.equal(glass.alphaMode,'BLEND');assert.equal(glass.pbrMetallicRoughness.baseColorFactor[3],.08);
assert(exportedDocument.meshes.every(m=>m.extras.explosionOffset.every(v=>v===0)));
assert(exportedDocument.meshes.some(m=>m.extras.motion?.translate?.[2]>0));
assert(exportedDocument.meshes.some(m=>m.name==='hollow-front-cover-with-optical-aperture'));
const output='/private/tmp/little-things-camera-roundtrip.glb';await fs.writeFile(output,new Uint8Array(exported));
console.log(JSON.stringify({exportedBytes:exported.byteLength,glassAlpha:glass.pbrMetallicRoughness.baseColorFactor[3],layerMetadataRetained:true,output},null,2));
